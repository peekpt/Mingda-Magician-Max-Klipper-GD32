#!/usr/bin/env python3
"""Generate mcu/hostlost.h: the 1-bit bitmaps the MCU shows when the host
stops talking to it (watchdog timeout). Run from the repo root:
    python3 tools/make_hostlost.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MCU = os.path.normpath(os.path.join(HERE, '..', 'mcu'))
_src = open(os.path.join(MCU, 'font8x14.h')).read()
FONT = [int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', _src)]


def pack(txt, scale):
    gw, gh = 8 * scale, 16 * scale
    W, H = len(txt) * gw, gh
    px = [[0] * W for _ in range(H)]
    for i, ch in enumerate(txt):
        g = FONT[(ord(ch) & 0xFF) * 16:(ord(ch) & 0xFF) * 16 + 16]
        for r in range(16):
            bits = g[r] if r < len(g) else 0
            if not bits:
                continue
            for c in range(8):
                if (bits << c) & 0x80:
                    for ry in range(scale):
                        y = r * scale + ry
                        for rx in range(scale):
                            px[y][i * gw + c * scale + rx] = 1
    data = bytearray()
    for y in range(H):
        row = bytearray((W + 7) // 8)
        for x in range(W):
            if px[y][x]:
                row[x // 8] |= 0x80 >> (x % 8)
        data += row
    return W, H, data


def emit(name, txt, scale, out):
    w, h, data = pack(txt, scale)
    out.append('#define %s_W %d' % (name, w))
    out.append('#define %s_H %d' % (name, h))
    out.append('static const uint8_t %s[] = {' % name.lower())
    line = []
    for v in data:
        line.append('%d' % v)
        if len(line) >= 16:
            out.append('    ' + ','.join(line) + ',')
            line = []
    if line:
        out.append('    ' + ','.join(line) + ',')
    out.append('};')
    out.append('')
    return w, h


def main():
    out = ['// generated by tools/make_hostlost.py - do not edit',
           '#pragma once', '#include <stdint.h>', '']
    emit('HLOST_TITLE', 'HOST LOST', 3, out)
    emit('HLOST_SUB', 'no data from the Pi', 1, out)
    open(os.path.join(MCU, 'hostlost.h'), 'w').write('\n'.join(out) + '\n')
    print('hostlost.h written')


if __name__ == '__main__':
    main()
